import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Export the current schema only: no migration history or user database access.
const ddl = execFileSync(
    process.execPath,
    [
        fileURLToPath(new URL("./bin.cjs", import.meta.resolve("drizzle-kit"))),
        "export",
        "--dialect=sqlite",
        "--schema=./src/sqlite/*schema.ts",
    ],
    { encoding: "utf8" },
)
    .replace(/CREATE TABLE /g, "CREATE TABLE IF NOT EXISTS ")
    .replace(/\n\);/g, "\n) STRICT;")
    .replace(/CREATE (UNIQUE )?INDEX /g, "CREATE $1INDEX IF NOT EXISTS ");
const path = "src/sqlite/schema.generated.ts";
const generated = execFileSync(
    process.execPath,
    [
        fileURLToPath(new URL("../bin/oxfmt", import.meta.resolve("oxfmt"))),
        "--stdin-filepath",
        path,
    ],
    {
        input:
            "// Generated by pnpm --filter @aiox/persistence schema:generate. Do not edit.\nexport const SCHEMA_SQL = " +
            JSON.stringify(ddl) +
            ";\n",
        encoding: "utf8",
    },
);
if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== generated)
        throw new Error(
            "Stale SQLite DDL. Run pnpm --filter @aiox/persistence schema:generate.",
        );
} else writeFileSync(path, generated);
