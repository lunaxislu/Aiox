import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const schemaPath = new URL("../src/sqlite/schema.ts", import.meta.url);
const hostSchemaPath = new URL("../src/sqlite/host-schema.ts", import.meta.url);
const outputPath = fileURLToPath(
    new URL("../src/sqlite/schema.generated.ts", import.meta.url),
);

const [{ generateDrizzleJson, generateMigration }, schema, hostSchema] =
    await Promise.all([
        import("drizzle-kit/payload/sqlite"),
        import(schemaPath.href),
        import(hostSchemaPath.href),
    ]);

const [emptySnapshot, currentSnapshot] = await Promise.all([
    generateDrizzleJson({}),
    generateDrizzleJson({ ...schema, ...hostSchema }),
]);
const statements = await generateMigration(emptySnapshot, currentSnapshot);

const sqliteStatements = statements.map((statement) => {
    if (/^CREATE TABLE /.test(statement)) {
        return statement
            .replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ")
            .replace(
                /^(\s*`[^`]+` text) PRIMARY KEY/gm,
                "$1 NOT NULL PRIMARY KEY",
            )
            .replace(/\);\s*$/, ") STRICT;");
    }
    if (/^CREATE (UNIQUE )?INDEX /.test(statement)) {
        return statement.replace(
            /^CREATE (UNIQUE )?INDEX /,
            "CREATE $1INDEX IF NOT EXISTS ",
        );
    }
    throw new Error(
        `Unexpected SQLite initialization statement: ${statement.slice(0, 80)}`,
    );
});

const generated = execFileSync(
    process.execPath,
    [
        fileURLToPath(new URL("../bin/oxfmt", import.meta.resolve("oxfmt"))),
        "--stdin-filepath",
        outputPath,
    ],
    {
        input:
            "// Generated by pnpm --filter @aiox/persistence schema:generate. Do not edit.\n" +
            "export const SCHEMA_STATEMENTS = " +
            JSON.stringify(sqliteStatements) +
            " as const;\n\n" +
            'export const SCHEMA_SQL = SCHEMA_STATEMENTS.join("\\n\\n");\n',
        encoding: "utf8",
    },
);

if (process.argv.includes("--check")) {
    if (readFileSync(outputPath, "utf8") !== generated) {
        throw new Error(
            "Stale SQLite DDL. Run pnpm --filter @aiox/persistence schema:generate.",
        );
    }
} else {
    writeFileSync(outputPath, generated);
}
